import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context={window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('operations_reference_v208.js','utf8'),context);
const ref=context.window.OPERATIONS_REFERENCE_V208;
const html=fs.readFileSync('index.html','utf8');
const ui=fs.readFileSync('operations_reference_ui_v208.js','utf8');

assert.equal(ref.version,'v208');
assert.equal(ref.inventory.length,172,'all non-heading inventory rows must be retained');
assert.equal(ref.recipes.length,125,'all beverage, food, and batch recipe rows must be retained');
assert.equal(ref.shelf_life.length,125,'the shelf-life reference table must be retained');

const can500=ref.inventory.find(x=>x.name==='500 캔');
assert.deepEqual([can500.minimum_text,can500.current_text,can500.order_text],['야창 2b','매장 1봉/ 야창 2b','창고 여분 보면서']);
const americano=ref.recipes.find(x=>x.menu_name==='아메리카노');
assert.equal(americano.variants.length,3);
assert.match(americano.variants.find(x=>x.label==='HOT(13oz)').content,/온수 225g/);
assert.match(americano.variants.find(x=>x.label==='ICED(1L)').content,/에스프레소4샷/);
const hotdog=ref.recipes.find(x=>x.menu_name==='치즈 치폴레 핫도그');
assert.equal(hotdog.source_version,'26.09.11');
assert.match(hotdog.variants[0].content,/눈꽃 치즈 50g/);
const milkLife=ref.shelf_life.find(x=>x.name==='우유');
assert.equal(milkLife.expiry_after,'3일');

const dataAt=html.indexOf('operations_reference_v208.js?v=20260927v213');
const appAt=html.indexOf('operations_v1.js?v=20260927v213');
const uiAt=html.indexOf('operations_reference_ui_v208.js?v=20260927v213');
assert.ok(dataAt>=0&&dataAt<appAt&&appAt<uiAt,'reference data, legacy operations, then reference UI must load in order');
assert.ok(html.includes('const APP_VERSION="v213"'));
assert.ok(ui.includes('HOT(13oz)')===false,'variant labels must come from source data, not hardcoded UI');
assert.ok(ui.includes('발주 필요 품목과 인하대점 재고 기준'));
assert.ok(ui.includes('공식 제조 기준과 직접 등록한 레시피'));
assert.ok(!ui.includes('admin-subtabs'),'reference renderer must not copy the admin tab bar');
assert.ok(!ui.includes('원본 재고'),'inventory summary switcher must not be rendered');
assert.ok(!ui.includes('공식 레시피'),'recipe summary switcher must not be rendered');
assert.ok(ui.includes('발주 필요'),'inventory order recommendations must be present');
assert.ok(ui.includes('ops-order-bars'),'inventory order graph must be present');
assert.ok(ui.includes('BE.inventoryManualSave'),'inventory create and edit must save through the management API');
assert.ok(ui.includes('+ 레시피 등록'),'recipe registration must be available on the main screen');
assert.ok(ui.includes('BE.recipeSave'),'recipe create and edit must save through the management API');
assert.ok(!ui.includes('originalRender("inventory")'),'inventory management must not switch to a second screen');
assert.ok(!ui.includes('originalRender("recipe")'),'recipe management must not switch to a second screen');
assert.ok(!ui.includes('9레시피 패널'),'source labels must not appear on recipe cards');
assert.ok(!ui.includes('10레시피 패널'),'source labels must not appear in recipe details');
assert.ok(ui.includes('ops-recipe-static'),'registered recipe cards must have a single edit entry point');
assert.ok(ui.includes('window.openHqProductModal'),'HQ product rollout must open as a modal');
assert.ok(ui.includes('+ 신제품 등록')&&ui.includes('− 제품 제거'),'HQ modal must expose product add and remove actions');
assert.ok(ui.includes('ops-hq-inventory-picker'),'new products must select recipe ingredients from inventory');
assert.ok(ui.includes('기존 카테고리')&&ui.includes('새 카테고리 생성'),'product editor must support existing and new categories');
assert.ok(ui.includes('hqLaunchDate')&&ui.includes('BE.hqProductSchedule'),'product editor must support scheduled rollout dates');
assert.ok(ui.includes('cleanExample'),'legacy example prefixes must be stripped from displayed data');
assert.ok(!ui.includes('tab==="products"'),'HQ rollout must not render as an admin tab');
console.log('operations reference v213 QA PASS');
