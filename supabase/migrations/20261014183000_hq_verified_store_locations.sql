-- Official franchise directory: only exact and unambiguous live-store names are imported.
-- This is additive; never mutate stores, owner mappings, payroll or attendance.
create table if not exists public.store_locations (
 store_id bigint primary key references public.stores(id) on delete restrict,
 address text not null check(length(trim(address))>5),
 province text not null check(length(trim(province))>0),
 district text not null default '',
 subdistrict text not null default '',
 source_url text not null,
 verified_at timestamptz not null default now()
);
alter table public.store_locations enable row level security;
revoke all on public.store_locations from public, anon, authenticated;
-- Public-schema SECURITY DEFINER is restricted to authenticated HQ identities at runtime.
create or replace function public.hq_store_locations_list()
returns table(store_id bigint,address text,province text,district text,subdistrict text)
language plpgsql security definer set search_path = public, pg_temp
as $function$
begin
 if auth.uid() is null or not public.is_hq_admin() then
   raise exception 'NOT_AUTHORIZED' using errcode='42501';
 end if;
 return query select l.store_id,l.address,l.province,l.district,l.subdistrict
 from public.store_locations l order by l.store_id;
end;
$function$;
revoke all on function public.hq_store_locations_list() from public, anon;
grant execute on function public.hq_store_locations_list() to authenticated;
