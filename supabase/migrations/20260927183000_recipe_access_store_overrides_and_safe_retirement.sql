create or replace function public.is_hq_admin()
returns boolean
language sql stable security definer set search_path='public','pg_temp'
as $function$
  select exists(
    select 1 from public.admin_users a
    where a.user_id=(select auth.uid()) and a.admin_role='HQ'
  )
$function$;

create or replace function public.can_manage_store(p_store_id bigint)
returns boolean
language sql stable security definer set search_path='public','pg_temp'
as $function$
  select exists(
    select 1 from public.admin_users a
    where a.user_id=(select auth.uid())
      and (a.admin_role='HQ' or (a.admin_role='STORE_MANAGER' and a.store_id=p_store_id))
  )
$function$;

create or replace function public.admin_context()
returns jsonb
language sql stable security definer set search_path='public','pg_temp'
as $function$
  select coalesce(
    (select jsonb_build_object('role',a.admin_role,'store_id',a.store_id,'email',a.email)
       from public.admin_users a where a.user_id=(select auth.uid())),
    jsonb_build_object('role',null,'store_id',null,'email',null)
  )
$function$;

