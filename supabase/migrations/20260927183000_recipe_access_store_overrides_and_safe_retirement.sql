  from public.attendance_events ae
  where ae.employee_id=p_employee_id order by ae.id desc limit 1;
  if coalesce(v_last_type,'OUT')<>'IN' then raise exception 'NOT_CLOCKED_IN'; end if;

  return query
  with base as (
    select p.id product_id,p.recipe_version_id,p.product_key menu_key,p.name menu_name,
      p.category,r.thumbnail_url,a.status assignment_status,a.retirement_requested_at,
      coalesce(jsonb_agg(jsonb_build_object(
        'item_id',i.id,'item_name',i.name,'unit',i.unit,'quantity',c.quantity
      ) order by i.name) filter(where i.id is not null),'[]'::jsonb) components
    from public.hq_products p
    join public.store_product_assignments a on a.product_id=p.id and a.store_id=p_store_id
    left join public.recipe_versions r on r.id=p.recipe_version_id
    left join public.recipe_components c on c.recipe_version_id=r.id
    left join public.inventory_items i on i.id=c.item_id
    where a.status in ('ACTIVE','RETIRING')
    group by p.id,p.recipe_version_id,p.product_key,p.name,p.category,r.thumbnail_url,a.status,a.retirement_requested_at
