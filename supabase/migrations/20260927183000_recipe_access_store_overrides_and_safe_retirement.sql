create or replace function public.protect_store_product_retirement()
returns trigger
language plpgsql set search_path='public','pg_temp'
as $function$
begin
  if old.status='ACTIVE' and new.status='DISCONTINUED' then
    new.status:='RETIRING';
    new.discontinued_at:=null;
    new.retirement_requested_at:=now();
    new.retirement_completed_at:=null;
  elsif new.status='ACTIVE' then
    new.retirement_requested_at:=null;
    new.retirement_completed_at:=null;
  end if;
  return new;
end
$function$;
drop trigger if exists protect_store_product_retirement on public.store_product_assignments;
create trigger protect_store_product_retirement
before update on public.store_product_assignments
for each row execute function public.protect_store_product_retirement();

create or replace function public.notify_store_product_retirement()
returns trigger
language plpgsql set search_path='public','pg_temp'
as $function$
declare v_name text;
begin
  if old.status is distinct from 'RETIRING' and new.status='RETIRING' then
    select name into v_name from public.hq_products where id=new.product_id;
    insert into public.store_notifications(store_id,notification_type,product_id,title,message)
    values(new.store_id,'PRODUCT_RETIRING',new.product_id,
      coalesce(v_name,'상품')||' 판매 종료 안내',
      '전용 재료 재고를 소진한 뒤 레시피 화면에서 판매 종료를 확정하세요.');
  end if;
  return new;
end
$function$;
drop trigger if exists notify_store_product_retirement on public.store_product_assignments;
create trigger notify_store_product_retirement
after update on public.store_product_assignments
for each row execute function public.notify_store_product_retirement();

create or replace function public.keep_inventory_for_retiring_products()
returns trigger
language plpgsql set search_path='public','pg_temp'
as $function$
begin
  if old.is_active and not new.is_active and exists(
    select 1 from public.hq_product_items pi
    join public.store_product_assignments a on a.product_id=pi.product_id
    where pi.item_id=old.id and a.status='RETIRING'
  ) then new.is_active:=true; end if;
  return new;
end
$function$;
drop trigger if exists keep_inventory_for_retiring_products on public.inventory_items;
create trigger keep_inventory_for_retiring_products
before update of is_active on public.inventory_items
for each row execute function public.keep_inventory_for_retiring_products();

create or replace function public.admin_store_recipe_list(p_store_id bigint)
returns table(
  product_id bigint, recipe_version_id bigint, menu_key text, menu_name text,
  category text, thumbnail_url text, instructions jsonb, components jsonb, is_overridden boolean,
  assignment_status text, retirement_requested_at timestamptz
)
language plpgsql security definer set search_path='public','pg_temp'
as $function$
begin
  if not public.can_manage_store(p_store_id) then raise exception 'NOT_AUTHORIZED'; end if;
  return query
  with base as (
    select p.id product_id,p.recipe_version_id,p.product_key menu_key,p.name menu_name,
      p.category,r.thumbnail_url,a.status assignment_status,a.retirement_requested_at,
      coalesce(jsonb_agg(jsonb_build_object(
        'item_id',i.id,'item_name',i.name,'unit',i.unit,'quantity',c.quantity
      ) order by i.name) filter(where i.id is not null),'[]'::jsonb) components
    from public.hq_products p
    join public.store_product_assignments a on a.product_id=p.id and a.store_id=p_store_id
    left join public.recipe_versions r on r.id=p.recipe_version_id
    left join public.recipe_components c on c.recipe_version_id=r.id
    left join public.inventory_items i on i.id=c.item_id
    where a.status in ('ACTIVE','RETIRING')
    group by p.id,p.recipe_version_id,p.product_key,p.name,p.category,r.thumbnail_url,a.status,a.retirement_requested_at
  )
  select b.product_id,b.recipe_version_id,b.menu_key,
    coalesce(nullif(o.menu_name,''),b.menu_name),
    coalesce(nullif(o.category,''),b.category),
    coalesce(nullif(o.thumbnail_url,''),b.thumbnail_url),o.instructions,
    case when o.store_id is null then b.components else o.components end,
    o.store_id is not null,b.assignment_status,b.retirement_requested_at
  from base b left join public.store_recipe_overrides o
    on o.store_id=p_store_id and o.menu_key=b.menu_key
  order by coalesce(nullif(o.category,''),b.category) nulls last,
    coalesce(nullif(o.menu_name,''),b.menu_name);
end
$function$;

