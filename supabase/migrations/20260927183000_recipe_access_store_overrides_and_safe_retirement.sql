create or replace function public.admin_store_product_retirement_finalize(
  p_store_id bigint,p_product_id bigint
)
returns jsonb
language plpgsql security definer set search_path='public','pg_temp'
as $function$
declare v_positive jsonb; v_untracked jsonb;
begin
  if not public.can_manage_store(p_store_id) then raise exception 'NOT_AUTHORIZED'; end if;
  if not exists(select 1 from public.store_product_assignments where store_id=p_store_id and product_id=p_product_id and status='RETIRING') then
    raise exception 'RETIREMENT_NOT_PENDING';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('name',i.name,'on_hand',m.on_hand,'unit',m.unit)),'[]'::jsonb)
  into v_positive
  from public.hq_product_items pi
  join public.inventory_items i on i.id=pi.item_id
  join public.inventory_manual_items m on m.store_id=p_store_id and m.source_item_id=i.id and m.is_active
  where pi.product_id=p_product_id and pi.created_by_hq and m.on_hand>0;

  select coalesce(jsonb_agg(jsonb_build_object('item_id',i.id,'name',i.name)),'[]'::jsonb)
  into v_untracked
  from public.hq_product_items pi
  join public.inventory_items i on i.id=pi.item_id
  where pi.product_id=p_product_id and pi.created_by_hq
    and not exists(select 1 from public.inventory_manual_items m where m.store_id=p_store_id and m.source_item_id=i.id and m.is_active);

  if jsonb_array_length(v_positive)>0 then
    return jsonb_build_object('ok',false,'error','STOCK_REMAINS','items',v_positive);
  end if;
  if jsonb_array_length(v_untracked)>0 then
    return jsonb_build_object('ok',false,'error','STOCK_NOT_TRACKED','items',v_untracked);
  end if;

  update public.store_product_assignments set status='DISCONTINUED',discontinued_at=now(),retirement_completed_at=now()
  where store_id=p_store_id and product_id=p_product_id and status='RETIRING';

  update public.inventory_items i set is_active=false,updated_at=now()
  where exists(select 1 from public.hq_product_items pi where pi.product_id=p_product_id and pi.item_id=i.id and pi.created_by_hq)
    and not exists(
      select 1 from public.hq_product_items pi2 join public.hq_products p2 on p2.id=pi2.product_id
      where pi2.item_id=i.id and p2.id<>p_product_id and p2.status='ACTIVE'
    )
    and not exists(
      select 1 from public.store_product_assignments a
      join public.hq_product_items pi3 on pi3.product_id=a.product_id and pi3.item_id=i.id
      where a.status in ('ACTIVE','RETIRING')
    );
  return jsonb_build_object('ok',true,'status','DISCONTINUED');
end
$function$;

create or replace function public.admin_inventory_manual_save_v2(
  p_id bigint,p_store_id bigint,p_name text,p_sku text,p_category text,
  p_unit text,p_on_hand numeric,p_target_level numeric,p_reorder_point numeric,
  p_thumbnail_url text,p_source_item_id bigint default null
)
returns public.inventory_manual_items
language plpgsql security definer set search_path='public','pg_temp'
as $function$
declare r public.inventory_manual_items; v_source public.inventory_items%rowtype;
begin
  if not public.can_manage_store(p_store_id) then raise exception 'NOT_AUTHORIZED'; end if;
  if coalesce(p_on_hand,0)<0 or coalesce(p_target_level,0)<0 or coalesce(p_reorder_point,0)<0 then raise exception 'INVALID_STOCK'; end if;
  if coalesce(p_target_level,0)>0 and coalesce(p_reorder_point,0)>coalesce(p_target_level,0) then raise exception 'INVALID_REORDER_POINT'; end if;
  if p_source_item_id is not null then
    select * into v_source from public.inventory_items where id=p_source_item_id and is_active;
    if v_source.id is null then raise exception 'INVENTORY_ITEM_NOT_FOUND'; end if;
    p_name:=v_source.name; p_sku:=v_source.sku; p_unit:=v_source.unit;
  elsif nullif(trim(p_name),'') is null then
    raise exception 'NAME_REQUIRED';
  end if;
  if p_id is null then
    insert into public.inventory_manual_items(store_id,name,sku,category,unit,on_hand,target_level,reorder_point,thumbnail_url,source_item_id)
    values(p_store_id,trim(p_name),nullif(trim(p_sku),''),nullif(trim(p_category),''),coalesce(nullif(trim(p_unit),''),'ea'),coalesce(p_on_hand,0),coalesce(p_target_level,0),coalesce(p_reorder_point,0),nullif(trim(p_thumbnail_url),''),p_source_item_id)
    on conflict(store_id,name) do update set sku=excluded.sku,category=excluded.category,unit=excluded.unit,on_hand=excluded.on_hand,target_level=excluded.target_level,reorder_point=excluded.reorder_point,thumbnail_url=excluded.thumbnail_url,source_item_id=coalesce(excluded.source_item_id,public.inventory_manual_items.source_item_id),updated_at=now()
    returning * into r;
  else
    update public.inventory_manual_items set name=trim(p_name),sku=nullif(trim(p_sku),''),category=nullif(trim(p_category),''),unit=coalesce(nullif(trim(p_unit),''),'ea'),on_hand=coalesce(p_on_hand,0),target_level=coalesce(p_target_level,0),reorder_point=coalesce(p_reorder_point,0),thumbnail_url=nullif(trim(p_thumbnail_url),''),source_item_id=coalesce(p_source_item_id,source_item_id),updated_at=now()
    where id=p_id and store_id=p_store_id returning * into r;
  end if;
  if r.id is null then raise exception 'INVENTORY_SAVE_FAILED'; end if;
  return r;
end
$function$;

