$function$;

create or replace function public.admin_store_recipe_override_save(
  p_store_id bigint,p_menu_key text,p_menu_name text,p_category text,
  p_components jsonb,p_thumbnail_url text,p_instructions jsonb default null
)
returns jsonb
language plpgsql security definer set search_path='public','pg_temp'
as $function$
declare v_comp jsonb; v_item public.inventory_items%rowtype; v_normalized jsonb='[]'::jsonb;
begin
  if not public.can_manage_store(p_store_id) then raise exception 'NOT_AUTHORIZED'; end if;
  if not exists(
    select 1 from public.hq_products p join public.store_product_assignments a on a.product_id=p.id
    where p.product_key=p_menu_key and a.store_id=p_store_id and a.status in ('ACTIVE','RETIRING')
  ) then raise exception 'RECIPE_NOT_FOUND'; end if;
  if jsonb_typeof(p_components)<>'array' or jsonb_array_length(p_components)=0 then
    raise exception 'COMPONENT_REQUIRED';
  end if;
  for v_comp in select * from jsonb_array_elements(p_components) loop
    select * into v_item from public.inventory_items
    where id=nullif(v_comp->>'item_id','')::bigint and is_active;
    if v_item.id is null or coalesce((v_comp->>'quantity')::numeric,0)<=0 then
      raise exception 'INVALID_COMPONENT';
    end if;
    v_normalized:=v_normalized||jsonb_build_array(jsonb_build_object(
      'item_id',v_item.id,'item_name',v_item.name,'unit',v_item.unit,
      'quantity',(v_comp->>'quantity')::numeric
    ));
  end loop;
  if p_instructions is not null and jsonb_typeof(p_instructions)<>'array' then
    raise exception 'INVALID_INSTRUCTIONS';
  end if;
  insert into public.store_recipe_overrides(
    store_id,menu_key,menu_name,category,thumbnail_url,instructions,components,updated_by,updated_at
  ) values(
    p_store_id,p_menu_key,nullif(trim(p_menu_name),''),nullif(trim(p_category),''),
    nullif(trim(p_thumbnail_url),''),p_instructions,v_normalized,auth.uid(),now()
  ) on conflict(store_id,menu_key) do update set
    menu_name=excluded.menu_name,category=excluded.category,
    thumbnail_url=excluded.thumbnail_url,instructions=excluded.instructions,components=excluded.components,
    updated_by=auth.uid(),updated_at=now();
  return jsonb_build_object('ok',true,'store_id',p_store_id,'menu_key',p_menu_key);
end
$function$;

create or replace function public.admin_store_recipe_override_clear(
