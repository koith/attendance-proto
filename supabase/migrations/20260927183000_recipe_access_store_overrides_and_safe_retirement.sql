    coalesce(nullif(o.category,''),b.category),
    coalesce(nullif(o.thumbnail_url,''),b.thumbnail_url),o.instructions,
    case when o.store_id is null then b.components else o.components end,
    b.assignment_status,b.retirement_requested_at
  from base b left join public.store_recipe_overrides o
    on o.store_id=p_store_id and o.menu_key=b.menu_key
