-- Branch-scoped, auditable physical stocktake for existing real catalog items.
-- Additive objects only. No preexisting inventory rows, attendance or payroll
-- values are modified at migration time. Posting requires explicit manager call.
CREATE TABLE IF NOT EXISTS public.store_inventory_stocktakes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id bigint NOT NULL REFERENCES public.stores(id),
  counted_on date NOT NULL,
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','POSTED','CANCELLED')),
  note text,
  created_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  posted_at timestamptz
);
CREATE INDEX IF NOT EXISTS store_inventory_stocktakes_store_date_idx
  ON public.store_inventory_stocktakes(store_id,counted_on DESC,id DESC);

CREATE TABLE IF NOT EXISTS public.store_inventory_stocktake_lines (
  stocktake_id bigint NOT NULL REFERENCES public.store_inventory_stocktakes(id) ON DELETE RESTRICT,
  item_id bigint NOT NULL REFERENCES public.inventory_items(id) ON DELETE RESTRICT,
  counted_quantity numeric NOT NULL CHECK(counted_quantity>=0 AND counted_quantity<=1000000000),
  expected_quantity numeric NOT NULL,
  variance numeric NOT NULL,
  PRIMARY KEY(stocktake_id,item_id)
);
CREATE INDEX IF NOT EXISTS store_inventory_stocktake_lines_item_idx
  ON public.store_inventory_stocktake_lines(item_id);

ALTER TABLE public.store_inventory_stocktakes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_inventory_stocktake_lines ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.store_inventory_stocktakes FROM PUBLIC,anon,authenticated;
REVOKE ALL ON TABLE public.store_inventory_stocktake_lines FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.admin_store_stocktake_catalog(p_store_id bigint)
RETURNS TABLE(id bigint,name text,unit text,expected_quantity numeric)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $function$
BEGIN
 IF NOT public.can_manage_store(p_store_id) THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.stores s WHERE s.id=p_store_id AND s.is_active AND s.onboarding_status='READY')
 THEN RAISE EXCEPTION 'STORE_NOT_READY'; END IF;
 RETURN QUERY
 SELECT i.id,i.name,i.unit,COALESCE(sum(m.quantity),0)::numeric
 FROM public.inventory_items i
 LEFT JOIN public.inventory_movements m ON m.item_id=i.id
    AND (m.store_id=p_store_id OR (p_store_id=1 AND m.store_id IS NULL)) AND NOT m.is_demo
 WHERE i.is_active AND NOT i.is_demo
   AND NOT EXISTS(SELECT 1 FROM public.inventory_movements dm
      WHERE dm.item_id=i.id AND (dm.store_id=p_store_id OR (p_store_id=1 AND dm.store_id IS NULL))
        AND dm.is_demo)
 GROUP BY i.id,i.name,i.unit ORDER BY i.name;
END $function$;

CREATE OR REPLACE FUNCTION public.admin_store_stocktake_list(p_store_id bigint)
RETURNS TABLE(id bigint,counted_on date,status text,note text,created_at timestamptz,posted_at timestamptz,line_count bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $function$
BEGIN
 IF NOT public.can_manage_store(p_store_id) THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 RETURN QUERY
 SELECT h.id,h.counted_on,h.status,h.note,h.created_at,h.posted_at,
        (SELECT count(*) FROM public.store_inventory_stocktake_lines l WHERE l.stocktake_id=h.id)
 FROM public.store_inventory_stocktakes h WHERE h.store_id=p_store_id
 ORDER BY h.id DESC LIMIT 50;
END $function$;

CREATE OR REPLACE FUNCTION public.admin_store_stocktake_detail(p_store_id bigint,p_stocktake_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $function$
DECLARE v_header public.store_inventory_stocktakes%ROWTYPE;
BEGIN
 IF NOT public.can_manage_store(p_store_id) THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 SELECT * INTO v_header FROM public.store_inventory_stocktakes
 WHERE id=p_stocktake_id AND store_id=p_store_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'STOCKTAKE_NOT_FOUND'; END IF;
 RETURN jsonb_build_object(
  'id',v_header.id,'store_id',v_header.store_id,
  'counted_on',v_header.counted_on,'status',v_header.status,'note',v_header.note,
  'created_at',v_header.created_at,'posted_at',v_header.posted_at,
  'lines',COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'item_id',l.item_id,'name',i.name,'unit',i.unit,
      'counted_quantity',l.counted_quantity,'expected_quantity',l.expected_quantity,
      'variance',l.variance) ORDER BY i.name)
    FROM public.store_inventory_stocktake_lines l
    JOIN public.inventory_items i ON i.id=l.item_id
    WHERE l.stocktake_id=v_header.id
  ),'[]'::jsonb));
END $function$;

CREATE OR REPLACE FUNCTION public.admin_store_stocktake_draft(
 p_store_id bigint,p_lines jsonb,p_note text DEFAULT NULL
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $function$
DECLARE v_id bigint;v_user uuid;v_row jsonb;v_item_id bigint;v_qty numeric;v_expected numeric;v_count integer;
BEGIN
 IF NOT public.can_manage_store(p_store_id) THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.stores s WHERE s.id=p_store_id AND s.is_active AND s.onboarding_status='READY')
 THEN RAISE EXCEPTION 'STORE_NOT_READY'; END IF;
 v_user:=auth.uid();
 IF v_user IS NULL THEN RAISE EXCEPTION 'LOGIN_REQUIRED'; END IF;
 IF p_lines IS NULL OR jsonb_typeof(p_lines)<>'array' THEN RAISE EXCEPTION 'INVALID_STOCKTAKE_LINES'; END IF;
 v_count:=jsonb_array_length(p_lines);
 IF v_count<1 OR v_count>100 THEN RAISE EXCEPTION 'INVALID_STOCKTAKE_LINE_COUNT'; END IF;
 IF length(coalesce(p_note,''))>500 THEN RAISE EXCEPTION 'NOTE_TOO_LONG'; END IF;
 INSERT INTO public.store_inventory_stocktakes(store_id,counted_on,status,note,created_by)
 VALUES(p_store_id,(now() AT TIME ZONE 'Asia/Seoul')::date,'DRAFT',nullif(btrim(p_note),''),v_user)
 RETURNING id INTO v_id;
 FOR v_row IN SELECT value FROM jsonb_array_elements(p_lines)
 LOOP
   IF jsonb_typeof(v_row)<>'object'
      OR coalesce(v_row->>'item_id','') !~ '^[1-9][0-9]*$'
      OR jsonb_typeof(v_row->'counted_quantity') IS DISTINCT FROM 'number'
   THEN RAISE EXCEPTION 'INVALID_STOCKTAKE_ITEM'; END IF;
   v_item_id:=(v_row->>'item_id')::bigint;
   v_qty:=(v_row->>'counted_quantity')::numeric;
   IF v_qty<0 OR v_qty>1000000000 THEN RAISE EXCEPTION 'INVALID_COUNTED_QUANTITY'; END IF;
   IF NOT EXISTS(SELECT 1 FROM public.inventory_items i WHERE i.id=v_item_id AND i.is_active AND NOT i.is_demo)
   THEN RAISE EXCEPTION 'REAL_ACTIVE_ITEM_REQUIRED'; END IF;
   IF EXISTS(SELECT 1 FROM public.inventory_movements m
     WHERE m.item_id=v_item_id AND (m.store_id=p_store_id OR (p_store_id=1 AND m.store_id IS NULL))
       AND m.is_demo)
   THEN RAISE EXCEPTION 'DEMO_STOCK_NEEDS_REVIEW'; END IF;
   IF EXISTS(SELECT 1 FROM public.store_inventory_stocktake_lines l
     WHERE l.stocktake_id=v_id AND l.item_id=v_item_id)
   THEN RAISE EXCEPTION 'DUPLICATE_STOCKTAKE_ITEM'; END IF;
   SELECT COALESCE(sum(m.quantity),0) INTO v_expected
   FROM public.inventory_movements m WHERE m.item_id=v_item_id
     AND (m.store_id=p_store_id OR (p_store_id=1 AND m.store_id IS NULL))
     AND NOT m.is_demo;
   INSERT INTO public.store_inventory_stocktake_lines(stocktake_id,item_id,counted_quantity,expected_quantity,variance)
   VALUES(v_id,v_item_id,v_qty,v_expected,v_qty-v_expected);
 END LOOP;
 RETURN public.admin_store_stocktake_detail(p_store_id,v_id);
END $function$;

CREATE OR REPLACE FUNCTION public.admin_store_stocktake_post(
 p_store_id bigint,p_stocktake_id bigint
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public','pg_temp'
AS $function$
DECLARE v_h public.store_inventory_stocktakes%ROWTYPE;v_line record;v_current numeric;v_variance numeric;v_movements integer:=0;
BEGIN
 IF NOT public.can_manage_store(p_store_id) THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.stores s WHERE s.id=p_store_id AND s.is_active AND s.onboarding_status='READY')
 THEN RAISE EXCEPTION 'STORE_NOT_READY'; END IF;
 IF auth.uid() IS NULL THEN RAISE EXCEPTION 'LOGIN_REQUIRED'; END IF;
 SELECT * INTO v_h FROM public.store_inventory_stocktakes
 WHERE id=p_stocktake_id AND store_id=p_store_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'STOCKTAKE_NOT_FOUND'; END IF;
 IF v_h.status='POSTED' THEN
   RETURN jsonb_build_object('ok',true,'id',v_h.id,'status','POSTED','already_posted',true);
 END IF;
 IF v_h.status<>'DRAFT' THEN RAISE EXCEPTION 'STOCKTAKE_NOT_DRAFT'; END IF;
 IF v_h.counted_on<>(now() AT TIME ZONE 'Asia/Seoul')::date
 THEN RAISE EXCEPTION 'STOCKTAKE_EXPIRED_RECOUNT'; END IF;
 PERFORM pg_advisory_xact_lock(hashtext('stocktake_store_'||p_store_id::text));
 FOR v_line IN SELECT l.* FROM public.store_inventory_stocktake_lines l
   WHERE l.stocktake_id=v_h.id ORDER BY l.item_id
 LOOP
   IF NOT EXISTS(SELECT 1 FROM public.inventory_items i
     WHERE i.id=v_line.item_id AND i.is_active AND NOT i.is_demo)
   THEN RAISE EXCEPTION 'REAL_ACTIVE_ITEM_REQUIRED'; END IF;
   IF EXISTS(SELECT 1 FROM public.inventory_movements m
      WHERE m.item_id=v_line.item_id
        AND (m.store_id=p_store_id OR (p_store_id=1 AND m.store_id IS NULL)) AND m.is_demo)
   THEN RAISE EXCEPTION 'DEMO_STOCK_NEEDS_REVIEW'; END IF;
   SELECT COALESCE(sum(m.quantity),0) INTO v_current
   FROM public.inventory_movements m WHERE m.item_id=v_line.item_id
      AND (m.store_id=p_store_id OR (p_store_id=1 AND m.store_id IS NULL))
      AND NOT m.is_demo;
   IF v_current<>v_line.expected_quantity THEN
      RAISE EXCEPTION 'STOCK_CHANGED_RECOUNT';
   END IF;
   v_variance:=v_line.counted_quantity-v_current;
   IF v_variance<>0 THEN
     INSERT INTO public.inventory_movements(
       store_id,item_id,business_date,movement_type,quantity,
       source_type,source_key,note,is_demo)
     VALUES(p_store_id,v_line.item_id,v_h.counted_on,'COUNT',v_variance,
       'STORE_STOCKTAKE','store:'||p_store_id||':stocktake:'||v_h.id||':item:'||v_line.item_id,
       '확인된 재고 실사 #'||v_h.id,false);
     v_movements:=v_movements+1;
   END IF;
 END LOOP;
 UPDATE public.store_inventory_stocktakes
 SET status='POSTED',posted_at=now() WHERE id=v_h.id AND status='DRAFT';
 RETURN jsonb_build_object('ok',true,'id',v_h.id,'status','POSTED','adjustments',v_movements);
END $function$;

