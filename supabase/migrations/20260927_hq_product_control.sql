where menu_name ~ '^\s*\[예시\]';

-- Demo fixtures stay out of the registered management list; historical rows remain intact.
create or replace function public.admin_recipe_list_v2()
returns table(id bigint, menu_key text, menu_name text, category text, effective_from date, effective_to date, is_demo boolean, thumbnail_url text, components jsonb)
language plpgsql security definer set search_path='public','pg_temp'
as $function$
begin
  if not public.is_admin() then raise exception 'NOT_AUTHORIZED'; end if;
  return query select r.id,r.menu_key,r.menu_name,r.category,r.effective_from,r.effective_to,r.is_demo,r.thumbnail_url,
    coalesce(jsonb_agg(jsonb_build_object('item_id',i.id,'item_name',i.name,'unit',i.unit,'quantity',c.quantity) order by i.name)
      filter(where i.id is not null),'[]'::jsonb)
  from public.recipe_versions r
  left join public.recipe_components c on c.recipe_version_id=r.id
  left join public.inventory_items i on i.id=c.item_id
  where r.effective_to is null and not r.is_demo
  group by r.id order by r.menu_name,r.effective_from desc;
end
$function$;

