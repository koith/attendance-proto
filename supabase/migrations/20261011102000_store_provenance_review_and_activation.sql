-- Formal human-verification gate for nationwide Baekeok stores.
-- Demo catalog rows are NOT activated or rewritten by this migration.
CREATE TABLE IF NOT EXISTS public.store_provenance_reviews(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id bigint NOT NULL REFERENCES public.stores(id),
  decision text NOT NULL CHECK(decision IN ('VERIFIED','REJECTED')),
  evidence_reference text NOT NULL CHECK(length(btrim(evidence_reference))>=15),
  reviewed_by uuid NOT NULL REFERENCES auth.users(id),
  reviewed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS store_provenance_reviews_latest_idx
  ON public.store_provenance_reviews(store_id,id DESC);
ALTER TABLE public.store_provenance_reviews ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.store_provenance_reviews FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.store_provenance_reviews_id_seq FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.hq_store_provenance_review(
 p_store_id bigint,p_decision text,p_evidence_reference text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public','pg_temp'
AS $function$
DECLARE v_id bigint;v_status text;v_evidence text;
BEGIN
 IF NOT public.is_hq_admin() THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 IF p_store_id IS NULL OR p_store_id=1 THEN RAISE EXCEPTION 'PROTECTED_STORE'; END IF;
 IF p_decision NOT IN ('VERIFIED','REJECTED') THEN RAISE EXCEPTION 'INVALID_DECISION'; END IF;
 v_evidence:=btrim(coalesce(p_evidence_reference,''));
 IF length(v_evidence)<15 OR length(v_evidence)>2000 THEN
   RAISE EXCEPTION 'EVIDENCE_REFERENCE_REQUIRED'; END IF;
 SELECT s.onboarding_status INTO v_status FROM public.stores s
   WHERE s.id=p_store_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'STORE_NOT_FOUND'; END IF;
 IF v_status='READY' AND p_decision='REJECTED' THEN
   RAISE EXCEPTION 'SUSPEND_STORE_BEFORE_REJECTION'; END IF;
 INSERT INTO public.store_provenance_reviews
   (store_id,decision,evidence_reference,reviewed_by)
 VALUES(p_store_id,p_decision,v_evidence,auth.uid())
 RETURNING id INTO v_id;
 RETURN jsonb_build_object('ok',true,'review_id',v_id,'store_id',p_store_id,
                           'decision',p_decision);
END $function$;

CREATE OR REPLACE FUNCTION public.hq_store_provenance_list()
RETURNS TABLE(store_id bigint,decision text,evidence_reference text,reviewed_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public','pg_temp'
AS $function$
BEGIN
 IF NOT public.is_hq_admin() THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 RETURN QUERY
 SELECT DISTINCT ON (r.store_id) r.store_id,r.decision,
        r.evidence_reference,r.reviewed_at
 FROM public.store_provenance_reviews r
 ORDER BY r.store_id,r.id DESC;
END $function$;

-- Registration always remains STAGED. READY requires reviewed store identity,
-- a real owner account and no known demo employees.
CREATE OR REPLACE FUNCTION public.hq_store_onboarding_set(p_store_id bigint,p_status text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public','pg_temp'
AS $function$
DECLARE v_name text;v_count bigint;v_review text;v_source text;
BEGIN
 IF NOT public.is_hq_admin() THEN RAISE EXCEPTION 'NOT_AUTHORIZED'; END IF;
 IF p_status NOT IN ('STAGED','READY','SUSPENDED') OR p_store_id IS NULL
 THEN RAISE EXCEPTION 'BAD_ONBOARDING_STATUS'; END IF;
 IF p_store_id=1 AND p_status<>'READY' THEN RAISE EXCEPTION 'INHA_PRODUCTION_LOCK'; END IF;
 SELECT s.name,s.source_store_key INTO v_name,v_source
   FROM public.stores s WHERE s.id=p_store_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'STORE_NOT_FOUND'; END IF;
 SELECT count(*) INTO v_count FROM public.admin_users a
   WHERE a.admin_role='STORE_MANAGER' AND a.store_id=p_store_id;
 IF p_status='READY' AND p_store_id<>1 THEN
   SELECT r.decision INTO v_review FROM public.store_provenance_reviews r
     WHERE r.store_id=p_store_id ORDER BY r.id DESC LIMIT 1;
   IF v_review IS DISTINCT FROM 'VERIFIED' THEN
     RAISE EXCEPTION 'PROVENANCE_VERIFICATION_REQUIRED'; END IF;
   IF EXISTS(SELECT 1 FROM public.employees e WHERE e.store_id=p_store_id
             AND (coalesce(e.memo,'') ILIKE '%데모%' OR e.name ILIKE '%테스트%'))
   THEN RAISE EXCEPTION 'DEMO_EMPLOYEES_REQUIRE_REVIEW'; END IF;
   IF v_count<1 THEN RAISE EXCEPTION 'STORE_MANAGER_REQUIRED'; END IF;
 END IF;
 UPDATE public.stores SET onboarding_status=p_status,
   is_active=(p_status='READY') WHERE id=p_store_id;
 RETURN jsonb_build_object('ok',true,'store_id',p_store_id,'name',v_name,
                           'status',p_status,'manager_count',v_count,
                           'provenance_verified',p_store_id=1 OR v_review='VERIFIED');
END $function$;

