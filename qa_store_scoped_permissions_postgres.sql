CREATE TABLE public.employees(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 store_id bigint REFERENCES public.stores(id),name text NOT NULL,
 employee_no integer,memo text,is_active boolean DEFAULT true
);
CREATE TABLE public.payroll_period(ym text,store_id bigint,status text,PRIMARY KEY(ym,store_id));
CREATE TABLE public.payroll_snapshot(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ym text,store_id bigint,
 employee_name text,gross_pay integer,net_pay integer,base_pay integer,juhyu_pay integer
);
CREATE TABLE public.correction_requests(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,employee_id bigint,
 kind text,note text,requested_at timestamp without time zone,requested_type text,
 status text DEFAULT 'PENDING',event_id bigint,created_at timestamptz DEFAULT now(),
 resolved_by text,resolved_at timestamptz,reject_reason text
);
CREATE TABLE public.event_corrections(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_id bigint,
 employee_id bigint,action text,new_event_at timestamp without time zone,
 new_event_type text,reason text,created_by text
);

