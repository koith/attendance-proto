import assert from 'node:assert/strict';
import fs from 'node:fs';
const src=fs.readFileSync('operations_v1.js','utf8');
assert.doesNotMatch(src,/demoInventoryRatios|catalogForStore|inventoryCatalog|estimatedRecipe/,'production inventory/recipe screens must not invent stock or ingredient amounts');
assert.match(src,/BE\.inventoryOverview\(\)/,'load inventory from store-scoped backend');
assert.match(src,/BE\.inventoryManualList\(\)/,'load manual inventory from backend');
const match=src.match(/const withCatalog=(.*?);\s*function shell\(/s);
assert.ok(match,'extract the real production inventory filtering function');
const withCatalog=Function('return ('+match[1]+')')();
const stored=[{id:1,name:'확인된 재고',on_hand:27},{id:2,name:'[예시] 가상 품목',on_hand:1000},{id:3,name:'시연 품목',is_demo:true,on_hand:2000}];
assert.deepEqual(withCatalog(stored),[stored[0]],'only actual, non-demo rows may appear, with unmodified quantities');
assert.deepEqual(withCatalog([]),[],'no inventory must display empty, not synthetic quantities');
assert.deepEqual(withCatalog(null),[],'backend absence cannot fabricate stock');
const recipe=src.match(/const recipeComponents=(.*?);\s*const withCatalog=/s);
assert.ok(recipe,'extract the recipe-component fallback');
const recipeComponents=Function('return ('+recipe[1]+')')();
assert.deepEqual(recipeComponents({menu_name:'카페라떼',components:[]}),[],'unknown recipe quantities are not guessed from menu names');
assert.deepEqual(recipeComponents({menu_name:'카페라떼',components:[{item_name:'우유',quantity:230,unit:'ml'}]}),[{item_name:'우유',quantity:230,unit:'ml'}]);
new Function(src);
console.log('PASS production inventory/recipe use only persisted data; no synthetic stock or ingredient quantities');
