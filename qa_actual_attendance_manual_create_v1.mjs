import fs from 'node:fs';
import assert from 'node:assert/strict';
const s=fs.readFileSync('actual_attendance.js','utf8');
const begin=s.indexOf('async function addAttendance(day)');
const end=s.indexOf('function openCorrection(day,s)',begin);
assert(begin>=0&&end>begin,'manual attendance handler must exist');
const fn=s.slice(begin,end);
assert(fn.includes('const validClock=t=>'),'HH:MM validator must exist');
assert(fn.includes('if(!validClock(inTime))'),'IN time validated');
assert(fn.includes('if(outTime&&!validClock(outTime))'),'OUT time validated before write');
assert(fn.indexOf('if(outTime&&!validClock(outTime))')<fn.indexOf("await rpc('admin_correct_event'"),'reject invalid OUT before inserting IN');
assert(fn.includes('if(addedIn?.ok===false)'),'RPC logical errors must not show success');
assert(fn.includes('if(addedOut?.ok===false)'),'OUT logical errors must not show success');
assert(fn.includes('출근 기록만 저장됐습니다'),'partial writes must be disclosed');
assert(fn.includes('await loadMonth();renderDay(day)'),'refresh saved records');
assert(fn.includes('퇴근 날짜'),'cross-midnight OUT date explicit');
const validClock=t=>/^([01]\\d|2[0-3]):[0-5]\\d$/.test(t);
for(const v of ['00:00','09:00','17:30','23:59'])assert(validClock(v),v);
for(const v of ['9:00','24:00','23:60','09:0',''])assert(!validClock(v),v);
console.log('PASS manual attendance create: validation, partial failure, overnight, refresh');
