import assert from 'node:assert/strict';
import fs from 'node:fs';
const src=fs.readFileSync('operations_reference_ui_v208.js','utf8');
const start=src.indexOf('function stockOrderSuggestion(');
const end=src.indexOf('async function openPurchaseOrder(',start);
assert.ok(start>0&&end>start,'isolated safe suggestion helper exists');
const fn=(new Function(src.slice(start,end)+'\nreturn stockOrderSuggestion;'))();
const row={id:20,name:'QA_원두',unit:'g',stock_unit:'g',order_unit:'box',conversion_quantity:500,target_level:2000,on_hand:700};
const o=(quantity,received=0,attrs={})=>({item_id:20,manual_item_id:null,ordered_quantity:quantity,received_quantity:received,unit:'g',status:'ORDERED',...attrs});
assert.deepEqual([fn(row,[]).suggest,fn(row,[o(200)]).suggest],[1500,1500]);
const partial=fn(row,[o(750,250),o(450,200)]);
assert.equal(partial.pending,750);
assert.equal(partial.shortage,550);
assert.equal(partial.suggest,1000,'stock-unit recommendation rounds shortage to whole package');
const pendingFull=fn(row,[o(1500)]);
assert.equal(pendingFull.suggest,0,'already-ordered items must never be duplicated by default');
assert.equal(fn({...row,on_hand:2000},[]).suggest,0,'no shortage must suggest zero, not one');
assert.equal(fn({...row,on_hand:3000},[]).suggest,0,'overstock must suggest zero');
assert.equal(fn(row,[o(2,1,{unit:'box'})]).pending,500,'order units convert to stock units');
assert.equal(fn(row,[o(4,1,{unit:'box'})]).suggest,0,'multiple packages already cover shortage');
assert.equal(fn(row,[o(100,0,{status:'CANCELLED'})]).pending,0,'cancelled orders are ignored');
assert.equal(fn({...row,manual:true},[o(300)]).pending,0,'manual and catalog IDs may not collide');
assert.equal(fn({...row,manual:true},[o(300,0,{manual_item_id:20,item_id:null})]).pending,300);
assert.equal(fn(row,[o(100,0,{unit:'mystery'})]).valid,false,'unknown units fail closed');
assert.equal(fn(row,[o(100,120)]).valid,false,'overreceived orders fail closed');
assert.equal(fn({...row,conversion_quantity:0},[]).valid,true,'missing conversion falls back to item native unit');
assert.equal(fn({...row,on_hand:NaN},[]).valid,false);
for(const count of [null,undefined,'','  ',NaN,Infinity]){
 const out=fn({...row,on_hand:count},[]);
 assert.equal(out.valid,false,'unknown stock must never be considered measured zero: '+String(count));
 assert.equal(out.suggest,0,'unknown stock must not prompt purchase');
}
assert.equal(fn({...row,on_hand:0},[]).valid,true,'actual measured zero remains valid');
assert.equal(fn({...row,on_hand:0},[]).suggest,2000,'real measured zero must calculate target shortage');
const beginKnown=src.indexOf('const hasMeasuredStock=');
const endKnown=src.indexOf('const cleanExample=',beginKnown);
assert.ok(beginKnown>=0&&endKnown>beginKnown,'unified stock has independent unknown-state predicate');
const hasMeasuredStock=Function(src.slice(beginKnown,endKnown)+'\nreturn hasMeasuredStock;')();
assert.equal(hasMeasuredStock(null),false);
assert.equal(hasMeasuredStock(''),false);
assert.equal(hasMeasuredStock('  '),false);
assert.equal(hasMeasuredStock(NaN),false);
assert.equal(hasMeasuredStock(0),true);
assert.equal(hasMeasuredStock('0'),true);
assert.match(src,/if\(!hasMeasuredStock\(row\.on_hand\)\)return \{key:"unknown",label:"재고 미확인",rank:2\}/);
assert.match(src,/known\?num\(on\):"미확인"/,'source inventory card must show unknown instead of fake zero');
assert.match(src,/rec=stockOrderSuggestion\(row\)/,'purchase dialog and stock card must use validated recommendation');
assert.doesNotMatch(src,/suggest=Math\.max\(1,target-on\)/,'never default to an unnecessary unit of purchase');
assert.match(src,/rec\.valid\?'':'disabled'/,'invalid suggestion must disable order creation control');
console.log('PASS MTG-10 safe pending purchase order, pack quantity, partial receiving, matching, duplicate guard');
