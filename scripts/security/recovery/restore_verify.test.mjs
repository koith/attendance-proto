 assert.equal(r.result,'PASS',JSON.stringify(r.stages.find(s=>!s.ok)||r.error));
 const st=Object.fromEntries(r.stages.map(s=>[s.stage,s]));
 assert.equal(st.digests.storage_objects,1);
 assert.equal(st.scope.completeness,'BACKUP_SCOPE_METADATA_PRESENT');
 assert.ok(st.pg_restore.excluded['provider-managed schema :: cron']>0,'managed schema excluded, not replayed');
