function reseal(mutate,name){
 const work=join(ctx.base,name);mkdirSync(work);mkdirSync(join(work,'x'));
 execFileSync(process.execPath,[join(ROOT,'scripts/security/unseal.mjs'),join(ctx.base,'full.sealed'),join(ctx.base,'priv.pem'),join(work,'a.tar.gz')]);
 execFileSync('tar',['-xzf',join(work,'a.tar.gz'),'-C',join(work,'x')]);
 mutate(join(work,'x'));
 execFileSync('tar',['-czf',join(work,'b.tar.gz'),'-C',join(work,'x'),'.']);
 execFileSync(process.execPath,[join(ROOT,'scripts/security/seal.mjs'),join(work,'b.tar.gz'),join(ctx.base,'pub.pem'),join(work,'b.sealed')]);
 return join(work,'b.sealed');
}

